/**
 * Generates the GitHub wiki pages for the components (docs/wiki/).
 *
 * For every row of common/src/main/resources/components.manifest.json it
 *   - renders the component as dropped from the palette, and every example in
 *     docs/wiki/examples/<LastIdSegment>.json, through the built bundle in headless Chromium,
 *     and writes a screenshot to docs/wiki/images/<LastIdSegment>/<example id | "default">.png;
 *   - writes one wiki page, docs/wiki/<Component-Name>.md;
 * and it writes Home.md (gallery) and _Sidebar.md.
 *
 * Sources (edit these, never the generated pages):
 *   docs/wiki/examples/<LastIdSegment>.json   [{ id, label, description, props, howTo? }, ...]
 *   docs/wiki/notes/<LastIdSegment>.md        optional hand-written section, included in the page
 *   the manifest and the prop schemas in common/src/main/resources/
 * Every other page in docs/wiki/ (Getting-Started.md, Binding-Data.md, ...) is hand-written and is
 * left alone: only files that carry the "Generated by" marker are ever overwritten or removed.
 *
 * Idempotent: a page is rewritten only when its text changes and an image only when its pixels
 * change, so running it twice produces no diff. Pages and images whose source is gone are removed.
 *
 * Run `npm run build` first, then `npm run wiki`.
 * Needs Playwright with Chromium available to Node; it is not a dependency of this package.
 * Images are scaled to at most 480 px wide, reduced to a 64-colour palette and written as
 * indexed PNG without metadata by this script itself; no external image tool is used.
 */
