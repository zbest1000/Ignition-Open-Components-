const readJson = file => JSON.parse(fs.readFileSync(file, 'utf8'));
const simpleName = id => id.slice(id.lastIndexOf('.') + 1);
const pageName = name => name.replace(/[^A-Za-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const isObject = value => value !== null && typeof value === 'object' && !Array.isArray(value);

class SourceError extends Error {}

function loadExamples(row) {
    const file = path.join(examplesDir, `${simpleName(row.id)}.json`);
    if (!fs.existsSync(file)) return [];
    const where = path.relative(repoDir, file);
    let parsed;
    try {
        parsed = readJson(file);
    } catch (e) {
        throw new SourceError(`${where} is not valid JSON: ${e.message}`);
    }
    if (!Array.isArray(parsed)) throw new SourceError(`${where} must contain a JSON array of examples.`);
    const ids = new Set();
    parsed.forEach((example, i) => {
        const at = `${where}, example #${i}`;
        if (!isObject(example)) throw new SourceError(`${at} is not an object.`);
        if (typeof example.id !== 'string' || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(example.id)) {
            throw new SourceError(`${at}: "id" must be lower-kebab-case (it names the image file).`);
        }
        if (example.id === 'default') throw new SourceError(`${at}: the id "default" is reserved for the default drop.`);
        if (ids.has(example.id)) throw new SourceError(`${at}: id "${example.id}" is used more than once.`);
        ids.add(example.id);
        if (typeof example.label !== 'string' || !example.label.trim()) throw new SourceError(`${at} ("${example.id}"): "label" is missing.`);
        if (!isObject(example.props)) throw new SourceError(`${at} ("${example.id}"): "props" must be an object.`);
        if (example.description !== undefined && typeof example.description !== 'string') {
            throw new SourceError(`${at} ("${example.id}"): "description" must be a string.`);
        }
        if (example.howTo !== undefined && !(Array.isArray(example.howTo) && example.howTo.every(s => typeof s === 'string'))) {
            throw new SourceError(`${at} ("${example.id}"): "howTo" must be an array of strings.`);
        }
    });
    return parsed;
}

/** The props a component has when it is dropped: the defaults of its schema, as Perspective applies them. */
function schemaDefaults(schema) {
    const walk = node => {
        if ('default' in node) return node.default;
        if (node.type === 'object' && node.properties) {
            const out = {};
            for (const [key, child] of Object.entries(node.properties)) {
                const value = walk(child);
                if (value !== undefined) out[key] = value;
            }
            return out;
        }
        return undefined;
    };
    const values = {};
    for (const [key, node] of Object.entries(schema.properties)) {
        const value = walk(node);
        if (value !== undefined) values[key] = value;
    }
    return values;
}

function loadSources() {
    const manifest = readJson(path.join(resourcesDir, 'components.manifest.json')).components;
    const pages = new Set();
    const components = manifest.map(row => {
        const schema = readJson(path.join(resourcesDir, row.schema));
        const ownProps = Object.keys(schema.properties).filter(key => !SHARED_PROPS.has(key));
        const component = {
            row,
            simple: simpleName(row.id),
            page: pageName(row.name),
            schema,
            ownProps,
            domain: ownProps.length > 0,
            referenceOnly: REFERENCE_ONLY.has(row.id),
            examples: [],
            notes: null,
        };
        if (pages.has(component.page)) throw new SourceError(`Two components would get the wiki page "${component.page}".`);
        pages.add(component.page);
        if (!component.referenceOnly) component.examples = loadExamples(row);
        const notes = path.join(notesDir, `${component.simple}.md`);
        if (fs.existsSync(notes)) component.notes = fs.readFileSync(notes, 'utf8').trim();
        return component;
    });

    const known = new Set(components.map(c => c.simple));
    for (const [dir, ext] of [[examplesDir, '.json'], [notesDir, '.md']]) {
        if (!fs.existsSync(dir)) continue;
        for (const file of fs.readdirSync(dir)) {
            if (path.extname(file) !== ext || known.has(path.basename(file, ext))) continue;
            throw new SourceError(`${path.relative(repoDir, path.join(dir, file))} does not belong to a component: ` +
                'the file name must be the last segment of a component id in the manifest (for example GaugeChart).');
        }
    }
    return components;
}

