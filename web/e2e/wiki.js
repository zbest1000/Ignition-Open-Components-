function bindingSection(option) {
    const targets = bindingTargets(option);
    if (targets.length === 0) {
        return ['The sample data is part of the option. To show live data, bind the parts of `option` that hold it ' +
            '(expand `option` in the Property Editor to find them); see [Binding Data](Binding-Data).'];
    }
    const shown = targets.slice(0, 8);
    const lines = [
        'Replace the sample data with live data by binding these paths (expand `option` in the Property Editor ' +
            'down to the property, then use its binding icon). Everything else in the option stays as pasted.',
        '',
        '   | Property | The binding must return |',
        '   |---|---|',
        ...shown.map(t => `   | \`props.option.${t.path}\` | ${cell(t.shape.text)} |`),
    ];
    if (targets.length > shown.length) {
        lines.push('', `   The remaining ${targets.length - shown.length} data properties of this example follow the same pattern.`);
    }
    const kinds = new Set();
    for (const target of shown) {
        const snippet = SNIPPETS[target.shape.kind];
        if (!snippet || kinds.has(target.shape.kind)) continue;
        kinds.add(target.shape.kind);
        lines.push('', ...snippet(target).map(line => (line ? `   ${line}` : '')));
    }
    const unscripted = shown.filter(t => !SNIPPETS[t.shape.kind]);
    if (unscripted.length > 0) {
        lines.push('', `   For ${unscripted.map(t => `\`${t.path}\``).join(', ')} build the same structure as the example in a ` +
            'script transform or a project script; [Binding Data](Binding-Data) shows the pattern.');
    }
    return lines;
}

function numbered(steps) {
    return steps.map((step, i) => {
        const [first, ...rest] = Array.isArray(step) ? step : [step];
        return [`${i + 1}. ${first}`, ...rest].join('\n') + (rest.length > 0 ? '\n' : '');
    }).join('\n');
}

function exampleSection(component, example) {
    const { row } = component;
    const { option, ...otherProps } = example.props;
    const out = [`### ${example.label}`, ''];
    if (example.description) out.push(example.description, '');
    out.push(`![${example.label}](${imagePath(component, example.id)})`, '', '**How to make it in Ignition**', '');

    const steps = [
        `In the Designer, drag **${row.name}** from the **${row.category}** group of the Perspective component palette onto a view.`,
    ];
    if (component.domain) {
        steps.push(`Select the component and set these props in the Property Editor (the JSON below lists them):\n\n   ${
            Object.keys(example.props).map(k => `\`${k}\``).join(', ')}`);
    } else {
        if (option) {
            steps.push('Open **Option JSON** below and copy it. In the Property Editor, right-click the `option` property and ' +
                'choose **Paste**: the pasted JSON replaces the sample option. (See [Getting Started](Getting-Started) for other ways to enter an option.)');
        }
        for (const [key, value] of Object.entries(otherProps)) {
            steps.push(`Set the \`${key}\` property to \`${JSON.stringify(value)}\`.`);
        }
        if (option) steps.push(bindingSection(option));
    }
    for (const note of example.howTo || []) steps.push(note);
    out.push(numbered(steps), '');

    if (component.domain) out.push(details('Props JSON', example.props));
    else if (option) out.push(details('Option JSON', option));
    return out.join('\n');
}

function typeOf(node) {
    let type = Array.isArray(node.type) ? node.type.join(' / ') : (node.type || 'any');
    if (node.type === 'array' && isObject(node.items) && typeof node.items.type === 'string') type = `array of ${node.items.type}`;
    return type;
}

function defaultOf(node) {
    if (!('default' in node)) return '';
    const text = JSON.stringify(node.default);
    if (text.length <= 40) return `\`${text}\``;
    return Array.isArray(node.default) ? `sample data (${node.default.length} items)` : 'sample data';
}

function propTable(component) {
    const lines = ['| Property | Type | Default | Description |', '|---|---|---|---|'];
    for (const key of component.ownProps) {
        const node = component.schema.properties[key];
        let description = node.description || '';
        if (Array.isArray(node.enum)) description += ` One of: ${node.enum.map(v => `\`${JSON.stringify(v)}\``).join(', ')}.`;
        lines.push(`| \`${key}\` | ${cell(typeOf(node))} | ${cell(defaultOf(node))} | ${cell(description.trim())} |`);
        if (node.type === 'object' && isObject(node.properties)) {
            for (const [sub, child] of Object.entries(node.properties)) {
                lines.push(`| \`${key}.${sub}\` | ${cell(typeOf(child))} | ${cell(defaultOf(child))} | ${cell(child.description || '')} |`);
            }
        }
    }
    return lines.join('\n');
}

