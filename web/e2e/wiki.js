/** Reduces RGBA pixels (alpha ignored; screenshots are opaque) to at most maxColors by median cut. */
function quantise(rgba, maxColors) {
    const counts = new Map();
    for (let i = 0; i < rgba.length; i += 4) {
        const key = (rgba[i] << 16) | (rgba[i + 1] << 8) | rgba[i + 2];
        counts.set(key, (counts.get(key) || 0) + 1);
    }
    const colors = [...counts.entries()].map(([key, n]) => ({ r: key >> 16, g: (key >> 8) & 255, b: key & 255, n, key }));
    colors.sort((a, b) => a.key - b.key);

    let boxes = [colors];
    if (colors.length > maxColors) {
        const spread = box => {
            let best = { channel: 'r', range: -1 };
            for (const channel of ['r', 'g', 'b']) {
                let min = 255, max = 0;
                for (const c of box) {
                    if (c[channel] < min) min = c[channel];
                    if (c[channel] > max) max = c[channel];
                }
                if (max - min > best.range) best = { channel, range: max - min };
            }
            return best;
        };
        const weight = box => box.reduce((sum, c) => sum + c.n, 0);
        while (boxes.length < maxColors) {
            // Split the box that covers the most pixels among those that still span more than one colour.
            let pick = -1, pickScore = -1, pickSpread = null;
            boxes.forEach((box, i) => {
                if (box.length < 2) return;
                const s = spread(box);
                const score = weight(box) * (s.range + 1);
                if (score > pickScore) { pick = i; pickScore = score; pickSpread = s; }
            });
            if (pick < 0) break;
            const box = boxes[pick];
            const channel = pickSpread.channel;
            box.sort((a, b) => a[channel] - b[channel] || a.key - b.key);
            const half = weight(box) / 2;
            let cut = 0, acc = 0;
            while (cut < box.length - 1 && acc + box[cut].n <= half) acc += box[cut++].n;
            cut = Math.max(1, cut);
            boxes.splice(pick, 1, box.slice(0, cut), box.slice(cut));
        }
    }
    let palette = colors.length <= maxColors
        ? colors.map(c => [c.r, c.g, c.b])
        : boxes.map(box => {
            let r = 0, g = 0, b = 0, n = 0;
            for (const c of box) { r += c.r * c.n; g += c.g * c.n; b += c.b * c.n; n += c.n; }
            return [Math.round(r / n), Math.round(g / n), Math.round(b / n)];
        });

    const nearest = c => {
        let best = 0, bestDistance = Infinity;
        for (let i = 0; i < palette.length; i++) {
            const p = palette[i];
            const d = (p[0] - c.r) ** 2 + (p[1] - c.g) ** 2 + (p[2] - c.b) ** 2;
            if (d < bestDistance) { best = i; bestDistance = d; }
        }
        return best;
    };
    // Two rounds of k-means move each palette colour to the centre of the pixels that use it.
    for (let round = 0; round < 2 && colors.length > maxColors; round++) {
        const sums = palette.map(() => [0, 0, 0, 0]);
        for (const c of colors) {
            const s = sums[nearest(c)];
            s[0] += c.r * c.n; s[1] += c.g * c.n; s[2] += c.b * c.n; s[3] += c.n;
        }
        palette = palette.map((p, i) => sums[i][3] ? sums[i].slice(0, 3).map(v => Math.round(v / sums[i][3])) : p);
    }
    const index = new Map();
    for (const c of colors) index.set(c.key, nearest(c));
    const pixels = Buffer.alloc(rgba.length / 4);
    for (let i = 0, p = 0; i < rgba.length; i += 4, p++) {
        pixels[p] = index.get((rgba[i] << 16) | (rgba[i + 1] << 8) | rgba[i + 2]);
    }
    return { palette, pixels };
}

const CRC_TABLE = (() => {
    const table = new Int32Array(256);
    for (let n = 0; n < 256; n++) {
        let c = n;
        for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
        table[n] = c;
    }
    return table;
})();

function crc32(buffer) {
    let c = -1;
    for (let i = 0; i < buffer.length; i++) c = CRC_TABLE[(c ^ buffer[i]) & 255] ^ (c >>> 8);
    return (c ^ -1) >>> 0;
}

const PNG_SIGNATURE = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);

function pngChunk(type, data) {
    const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
    const out = Buffer.alloc(8 + data.length + 4);
    out.writeUInt32BE(data.length, 0);
    body.copy(out, 4);
    out.writeUInt32BE(crc32(body), 8 + data.length);
    return out;
}

/** Writes an indexed PNG (colour type 3) with the smallest bit depth the palette allows and no metadata. */
function encodePng(width, height, palette, pixels) {
    const depth = palette.length <= 2 ? 1 : palette.length <= 4 ? 2 : palette.length <= 16 ? 4 : 8;
    const rowBytes = Math.ceil(width * depth / 8);
    const raw = Buffer.alloc((rowBytes + 1) * height); // filter type 0 on every row
    for (let y = 0; y < height; y++) {
        const row = y * (rowBytes + 1) + 1;
        for (let x = 0; x < width; x++) {
            const value = pixels[y * width + x];
            if (depth === 8) raw[row + x] = value;
            else raw[row + ((x * depth) >> 3)] |= value << (8 - depth - ((x * depth) & 7));
        }
    }
    const header = Buffer.alloc(13);
    header.writeUInt32BE(width, 0);
    header.writeUInt32BE(height, 4);
    header[8] = depth;
    header[9] = 3;
    return Buffer.concat([
        PNG_SIGNATURE,
        pngChunk('IHDR', header),
        pngChunk('PLTE', Buffer.from(palette.flat())),
        pngChunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
        pngChunk('IEND', Buffer.alloc(0)),
    ]);
}

/** Reads back a PNG written by encodePng as RGB triples; null for any other file. */
function decodePng(file) {
    try {
        if (!file.subarray(0, 8).equals(PNG_SIGNATURE)) return null;
        let width = 0, height = 0, depth = 0, palette = null;
        const data = [];
        for (let at = 8; at < file.length;) {
            const length = file.readUInt32BE(at);
            const type = file.toString('ascii', at + 4, at + 8);
            const body = file.subarray(at + 8, at + 8 + length);
            if (type === 'IHDR') {
                width = body.readUInt32BE(0);
                height = body.readUInt32BE(4);
                depth = body[8];
                if (body[9] !== 3 || body[12] !== 0) return null;
            } else if (type === 'PLTE') {
                palette = body;
            } else if (type === 'IDAT') {
                data.push(body);
            }
            at += 12 + length;
        }
        if (!palette || !width) return null;
        const raw = zlib.inflateSync(Buffer.concat(data));
        const rowBytes = Math.ceil(width * depth / 8);
        const rgb = Buffer.alloc(width * height * 3);
        for (let y = 0; y < height; y++) {
            const row = y * (rowBytes + 1);
            if (raw[row] !== 0) return null;
            for (let x = 0; x < width; x++) {
                const value = depth === 8
                    ? raw[row + 1 + x]
                    : (raw[row + 1 + ((x * depth) >> 3)] >> (8 - depth - ((x * depth) & 7))) & ((1 << depth) - 1);
                palette.copy(rgb, (y * width + x) * 3, value * 3, value * 3 + 3);
            }
        }
        return { width, height, rgb };
    } catch {
        return null;
    }
}

/**
 * Whether a stored image shows the same picture as a new one. WebGL charts are not drawn
 * identically pixel for pixel on every run, so a small number of slightly different pixels counts as "the same".
 */
function samePicture(stored, width, height, palette, pixels, tolerant) {
    if (!stored || stored.width !== width || stored.height !== height) return false;
    let different = 0;
    for (let p = 0; p < pixels.length; p++) {
        const c = palette[pixels[p]];
        const d = Math.max(Math.abs(stored.rgb[p * 3] - c[0]), Math.abs(stored.rgb[p * 3 + 1] - c[1]),
            Math.abs(stored.rgb[p * 3 + 2] - c[2]));
        if (d === 0) continue;
        if (!tolerant || d > 48) different++;
    }
    return tolerant ? different <= pixels.length * 0.002 : different === 0;
}

