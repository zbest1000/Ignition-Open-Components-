function startServer() {
    const server = http.createServer((req, res) => {
        const url = new URL(req.url, 'http://localhost');
        let file = null;
        if (url.pathname === '/') {
            res.writeHead(200, { 'Content-Type': 'text/html' });
            res.end(HARNESS_PAGE);
            return;
        }
        if (VENDOR[url.pathname]) {
            file = VENDOR[url.pathname];
        } else if (url.pathname.startsWith(MOUNT_URL)) {
            const resolved = path.resolve(mountedDir, url.pathname.slice(MOUNT_URL.length));
            if (resolved.startsWith(mountedDir + path.sep)) file = resolved;
        }
        if (!file || !fs.existsSync(file)) {
            res.writeHead(404);
            res.end('not found');
            return;
        }
        res.writeHead(200, { 'Content-Type': TYPES[path.extname(file)] || 'application/octet-stream' });
        fs.createReadStream(file).pipe(res);
    });
    return new Promise(resolve => server.listen(0, '127.0.0.1', () => resolve(server)));
}

const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));

/** The props to mount for a screenshot: the entry's props, with ECharts animation switched off. */
function screenshotProps(component, props) {
    const values = component.domain ? { ...schemaDefaults(component.schema), ...props } : { ...props };
    if (isObject(values.option) && Object.keys(values.option).length > 0) {
        values.option = { ...values.option, animation: false };
    }
    return JSON.parse(JSON.stringify(values));
}

/**
 * Mounts one entry and returns its picture as RGBA pixels, scaled to at most IMAGE_WIDTH.
 * The page's clock is driven by hand, so a chart is always captured at the same moment of its
 * animation (domain components animate; effects such as ripples never stop).
 */
async function capture(page, component, props, problems) {
    const { width, height } = component.row.size;
    const outWidth = Math.min(IMAGE_WIDTH, width);
    const outHeight = Math.round(height * outWidth / width);
    const label = `${component.row.id}`;

    problems.length = 0;
    await page.evaluate(([id, values, w, h]) => window.harness.render(id, values, w, h),
        [component.row.id, screenshotProps(component, props), width, height]);

    let state = { drawn: false, alert: null, loading: false };
    for (let waited = 0; waited < 20000 && !(state.drawn && !state.loading) && !state.alert; waited += 50) {
        await page.clock.runFor(100);
        await sleep(50); // real time: the echarts-gl chunk comes over the network
        state = await page.evaluate(() => window.harness.state());
    }
    const issues = [];
    if (state.alert) issues.push(`the chart shows an error: ${state.alert}`);
    else if (!state.drawn) issues.push('nothing was drawn');

    // Let animations finish (ECharts' default is one second) and WebGL charts refine their picture.
    await page.clock.runFor(component.row.gl ? 6000 : 3000);
    await sleep(component.row.gl ? 400 : 60);
    state = await page.evaluate(() => window.harness.state());
    if (state.alert && issues.length === 0) issues.push(`the chart shows an error: ${state.alert}`);
    issues.push(...problems);

    const shot = await page.locator('#host').screenshot();
    const rgba = Buffer.from(await page.evaluate(([b, w, h]) => window.harness.scale(b, w, h),
        [shot.toString('base64'), outWidth, outHeight]), 'base64');
    await page.evaluate(() => window.harness.remove());
    return { width: outWidth, height: outHeight, rgba, issues: issues.map(issue => `${label}: ${issue}`) };
}

