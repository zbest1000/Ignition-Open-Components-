/** Writes a generated page if its text changed. Refuses to overwrite a page that was written by hand. */
function writePage(name, text, stats) {
    const file = path.join(wikiDir, `${name}.md`);
    const content = `${text.replace(/[ \t]+$/gm, '').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
    if (fs.existsSync(file)) {
        const current = fs.readFileSync(file, 'utf8');
        if (!current.startsWith(MARKER)) {
            throw new SourceError(`docs/wiki/${name}.md exists and was not generated by this script; rename it or the component.`);
        }
        if (current === content) return;
    }
    fs.writeFileSync(file, content);
    stats.pagesWritten++;
}

function removeStale(pages, images, stats) {
    for (const file of fs.readdirSync(wikiDir)) {
        const full = path.join(wikiDir, file);
        if (path.extname(file) !== '.md' || !fs.statSync(full).isFile() || pages.has(path.basename(file, '.md'))) continue;
        if (fs.readFileSync(full, 'utf8').startsWith(MARKER)) {
            fs.unlinkSync(full);
            stats.removed.push(`docs/wiki/${file}`);
        }
    }
    if (!fs.existsSync(imagesDir)) return;
    for (const dir of fs.readdirSync(imagesDir)) {
        const full = path.join(imagesDir, dir);
        if (!fs.statSync(full).isDirectory()) continue;
        for (const file of fs.readdirSync(full)) {
            if (path.extname(file) === '.png' && !images.has(`images/${dir}/${file}`)) {
                fs.unlinkSync(path.join(full, file));
                stats.removed.push(`docs/wiki/images/${dir}/${file}`);
            }
        }
        if (fs.readdirSync(full).length === 0) fs.rmdirSync(full);
    }
}

async function main() {
    if (!fs.existsSync(path.join(mountedDir, 'OpenECharts.js'))) {
        console.error(`No bundle in ${mountedDir}. Run "npm run build" first.`);
        process.exit(2);
    }
    let chromium;
    try {
        ({ chromium } = require('playwright'));
    } catch {
        console.error('Playwright is not installed. Install it (with Chromium) to generate the wiki.');
        process.exit(2);
    }

    const components = loadSources();
    const stats = { pagesWritten: 0, imagesWritten: 0, removed: [] };
    const issues = [];
    const images = new Set();
    fs.mkdirSync(wikiDir, { recursive: true });

    const server = await startServer();
    const browser = await chromium.launch();
    try {
        const page = await browser.newPage({ viewport: { width: 1000, height: 800 }, deviceScaleFactor: DEVICE_SCALE });
        const problems = [];
        page.on('console', msg => { if (msg.type() === 'error') problems.push(`console: ${msg.text()}`); });
        page.on('pageerror', err => problems.push(`page error: ${err.message}`));
        await page.clock.install({ time: FROZEN_TIME });
        await page.goto(`http://127.0.0.1:${server.address().port}/`);
        await page.clock.pauseAt(FROZEN_TIME + 1000);

        for (const component of components) {
            const entries = [{ id: 'default', props: component.domain ? {} : (component.row.defaultOption ? { option: component.row.defaultOption } : {}) },
                ...component.examples];
            for (const entry of entries) {
                const relative = imagePath(component, entry.id);
                const shot = await capture(page, component, entry.props, problems);
                issues.push(...shot.issues.map(issue => `${relative}: ${issue}`));
                const { palette, pixels } = quantise(shot.rgba, MAX_COLORS);
                const file = path.join(wikiDir, relative);
                const stored = fs.existsSync(file) ? decodePng(fs.readFileSync(file)) : null;
                if (!samePicture(stored, shot.width, shot.height, palette, pixels, !!component.row.gl)) {
                    fs.mkdirSync(path.dirname(file), { recursive: true });
                    fs.writeFileSync(file, encodePng(shot.width, shot.height, palette, pixels));
                    stats.imagesWritten++;
                }
                images.add(relative);
            }
        }
    } finally {
        await browser.close();
        server.close();
    }

    const pages = new Set(['Home', '_Sidebar']);
    for (const component of components) {
        pages.add(component.page);
        writePage(component.page, componentPage(component), stats);
    }
    writePage('Home', homePage(components), stats);
    writePage('_Sidebar', sidebarPage(components), stats);
    removeStale(pages, images, stats);

    const bytes = [...images].reduce((sum, relative) => sum + fs.statSync(path.join(wikiDir, relative)).size, 0);
    const exampleCount = components.reduce((sum, c) => sum + c.examples.length, 0);
    console.log(`${components.length} component pages (+ Home, _Sidebar), ${exampleCount} examples.`);
    console.log(`${images.size} images, ${bytes} bytes in total (${Math.round(bytes / images.size)} on average).`);
    console.log(`Changed in this run: ${stats.pagesWritten} pages, ${stats.imagesWritten} images, ${stats.removed.length} removed.`);
    stats.removed.forEach(file => console.log(`  removed ${file}`));
    if (issues.length > 0) {
        console.error(`\n${issues.length} problem(s) while rendering:`);
        issues.forEach(issue => console.error(`  ${issue}`));
        process.exit(1);
    }
}

main().catch(err => {
    console.error(err instanceof SourceError ? `wiki: ${err.message}` : err);
    process.exit(1);
});
